export const GLYPH_W = 3;
export const GLYPH_H = 5;

/** 一段文本的像素宽度（含字间距） */
export function pixelTextWidth(text: string, scale = 1, spacing = 1): number {
  if (text.length === 0) return 0;
  return (text.length * (GLYPH_W + spacing) - spacing) * scale;
}

/**
 * 画点阵文本。只画得出数字/大写字母/上面列出的符号，其余字符画成空白。
 */
export function drawPixelText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  scale = 1,
  spacing = 1,
): void {
  ctx.fillStyle = color;
  let cx = Math.round(x);
  const cy = Math.round(y);
  const upper = text.toUpperCase();

  for (const ch of upper) {
    const glyph = GLYPHS[ch];
    if (glyph) {
      for (let row = 0; row < GLYPH_H; row++) {
        const line = glyph[row];
        for (let col = 0; col < GLYPH_W; col++) {
          if (line[col] === '1') {
            ctx.fillRect(cx + col * scale, cy + row * scale, scale, scale);
          }
        }
      }
    }
    cx += (GLYPH_W + spacing) * scale;
  }
}

/** 右对齐绘制（用于数字） */
export function drawPixelTextRight(
  ctx: CanvasRenderingContext2D,
  text: string,
  rightX: number,
  y: number,
  color: string,
  scale = 1,
): void {
  drawPixelText(ctx, text, rightX - pixelTextWidth(text, scale), y, color, scale);
}
